"""Town and city names -> country, for location text that names only a town ("Münster", "Deggendorf").

The table (cities.tsv, next to this file) is generated from GeoNames' cities5000 dump
(https://download.geonames.org/export/dump/, CC BY 4.0, attribution in the README):

    uv run python -m jobboard.gazetteer build cities5000.txt

A name is kept only when one country clearly owns it: its largest place there has at least
DOMINANCE times the population of the largest same-named place in any other country (counted over
the whole dump, so "Cambridge" weighs the UK against Massachusetts). European places count from 5,000
inhabitants; elsewhere from 100,000, enough to recognise a job as being outside Europe.
"""
from __future__ import annotations

import sys
import unicodedata
from collections import defaultdict
from functools import cache
from pathlib import Path

TABLE = Path(__file__).with_name("cities.tsv")
DOMINANCE = 5
MIN_POP_EUROPE, MIN_POP_ELSEWHERE = 5_000, 100_000
# Names that are also ordinary words in job location text: never a town on their own.
STOP = {"remote", "hybrid", "office", "home", "field", "mobile", "union", "independence", "enterprise",
        "paradise", "surprise", "temple", "spring", "best", "deal", "march", "street", "sale", "wells",
        "hope", "victoria", "of", "bar", "ede", "hem", "university", "college", "station", "centre",
        "center", "headquarters", "hq", "campus", "plant", "site", "online", "global", "europe", "nord",
        "sud", "south", "north", "east", "west", "central", "mitte", "perm", "can", "temp", "contract", "n/a"}


def key(text: str) -> str:
    """Same folding as places._key: case, accents and spacing don't matter."""
    folded = "".join(c for c in unicodedata.normalize("NFKD", text.casefold()) if not unicodedata.combining(c))
    return " ".join(folded.replace("-", " ").split())


def _variants(name: str) -> set[str]:
    """Spellings job boards use for the same town: 'Sankt Wendel' is also 'St. Wendel'."""
    out = {name}
    for long, shorts in (("Sankt ", ("St. ", "St ")), ("Saint-", ("St-", "St. ")), ("Saint ", ("St. ", "St "))):
        if name.startswith(long):
            out |= {short + name[len(long):] for short in shorts}
    return out


def build(dump: Path, europe: set[str], out: Path = TABLE) -> int:
    best: dict[str, dict[str, int]] = defaultdict(dict)   # name -> country -> largest population
    for line in dump.open(encoding="utf-8"):
        f = line.rstrip("\n").split("\t")
        country, pop = f[8], int(f[14] or 0)
        for name in {f[1], f[2]}:
            for variant in _variants(name):
                k = key(variant)
                best[k][country] = max(best[k].get(country, 0), pop)
    rows = []
    for k, by_country in best.items():
        if len(k) < 3 or k in STOP or not any(c.isalpha() for c in k):
            continue
        ranked = sorted(by_country.items(), key=lambda kv: -kv[1])
        country, pop = ranked[0]
        runner_up = ranked[1][1] if len(ranked) > 1 else 0
        floor = MIN_POP_EUROPE if country in europe else MIN_POP_ELSEWHERE
        if pop >= floor and pop >= DOMINANCE * runner_up:
            rows.append(f"{k}\t{country}")
    rows.sort()
    out.write_text("# name\tcountry. Generated by jobboard.gazetteer from GeoNames cities5000 (CC BY 4.0).\n"
                   + "\n".join(rows) + "\n", encoding="utf-8")
    return len(rows)


@cache
def table() -> dict[str, str]:
    if not TABLE.exists():
        return {}
    pairs = (line.split("\t") for line in TABLE.read_text(encoding="utf-8").splitlines()
             if line and not line.startswith("#"))
    return {name: country for name, country in pairs}


def country(name: str) -> str | None:
    return table().get(key(name))


def main(argv=None) -> int:
    args = sys.argv[1:] if argv is None else argv
    if len(args) != 2 or args[0] != "build":
        print("usage: python -m jobboard.gazetteer build cities5000.txt", file=sys.stderr)
        return 2
    from jobboard.places import EUROPE
    print(build(Path(args[1]), EUROPE), "names written to", TABLE)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
